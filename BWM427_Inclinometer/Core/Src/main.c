/**
 * @brief  The application entry point.
 * @retval int
 */
int main(void) {
	/* USER CODE BEGIN 1 */
	// Перед программным сбросом была команда boot (USB) — сразу в системный
	// загрузчик USB DFU, пока HAL и тактирование не тронуты. Иначе — возврат.
	usb_cli_boot_check();
	/* USER CODE END 1 */

	/* MCU Configuration--------------------------------------------------------*/

	/* Reset of all peripherals, Initializes the Flash interface and the Systick. */
	HAL_Init();

	/* USER CODE BEGIN Init */

	/* USER CODE END Init */

	/* Configure the system clock */
	SystemClock_Config();

	/* USER CODE BEGIN SysInit */

	/* USER CODE END SysInit */

	/* Initialize all configured peripherals */
	MX_GPIO_Init();
	MX_USART1_UART_Init();
	MX_I2C1_Init();
	MX_FATFS_Init();
	MX_ADC1_Init();
	MX_TIM3_Init();
	MX_SPI2_Init();
	MX_SPI1_Init();
	/* USER CODE BEGIN 2 */
	// Счётчик тактов DWT — для замера длительности прохода суперцикла
	CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
	DWT->CYCCNT = 0;
	DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;

	// USB CDC (виртуальный COM-порт): раньше остального, чтобы плату можно было
	// перевести в загрузчик, даже если дальше инициализация зависнет
	MX_USB_DEVICE_Init();

	// Энкодер (TIM3) и его кнопку (PA0) читает интерфейс (LVGL)
	HAL_TIM_Encoder_Start(&htim3, TIM_CHANNEL_ALL);

	// Часы, АЦП батареи, шина RS485, SD-карта
	app_init();

	// Дисплей и интерфейс
	ILI9341_Init();
	ui_init();
	/* USER CODE END 2 */

	/* Infinite loop */
	/* USER CODE BEGIN WHILE */
	while (1) {
		uint32_t c0 = DWT->CYCCNT;
		app_task(); // датчики, запись на SD, часы, батарея, тумблер
		uint32_t c1 = DWT->CYCCNT;
		ui_task();  // экран и энкодер
		app_diag_loop(c1 - c0, DWT->CYCCNT - c1);
		usb_cli_task(); // USB CDC: диагностика, переход в DFU
		/* USER CODE END WHILE */

		/* USER CODE BEGIN 3 */
	}
	/* USER CODE END 3 */
}

