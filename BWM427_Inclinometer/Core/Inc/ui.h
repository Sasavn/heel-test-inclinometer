/*
 * ui.h — интерфейс на LVGL (ILI9341 320x240 + энкодер TIM3 с кнопкой).
 */
#ifndef UI_H_
#define UI_H_

// Инициализировать LVGL, дисплей, энкодер и построить экраны.
// Вызывать после MX_*_Init() и ILI9341_Init().
void ui_init(void);

// Вызывать в каждом проходе суперцикла: обновляет виджеты из g_app
// (не чаще, чем нужно) и крутит lv_timer_handler().
void ui_task(void);

// Вызывать раз в 1 мс из SysTick: антидребезг кнопки энкодера и защёлка
// коротких нажатий, чтобы их не терять при долгом проходе суперцикла.
void ui_input_tick_1ms(void);

#endif /* UI_H_ */
